/*
 *
 *（无序区，有序区）。从无序区通过交换找出最大元素放到有序区前端。
 *
 * 选择排序思路：
 * 1. 比较相邻的元素。如果第一个比第二个大，就交换他们两个。
 * 2. 对每一对相邻元素作同样的工作，从开始第一对到结尾的最后一对。这步做完后，最后的元素会是最大的数。
 * 3. 针对所有的元素重复以上的步骤，除了最后一个。
 * 4. 持续每次对越来越少的元素重复上面的步骤，直到没有任何一对数字需要比较。
 *
 * 排序算法	平均时间复杂度	最差时间复杂度	空间复杂度	数据对象稳定性
 * 冒泡排序	  O(n2)	         O(n2)	        O(1)	    稳定
 * 数组：[5, 3, 8, 1]
 * 
 * 第1轮（i=0，j从0到2）：
 *   j=0：5 > 3 → 交换 → [3, 5, 8, 1]
 *   j=1：5 > 8 → 不换 → [3, 5, 8, 1]
 *   j=2：8 > 1 → 交换 → [3, 5, 1, 8]
 *   最大值8冒泡到最后 ✓
 * 
 * 第2轮（i=1，j从0到1）：
 *   j=0：3 > 5 → 不换 → [3, 5, 1, 8]
 *   j=1：5 > 1 → 交换 → [3, 1, 5, 8]
 *   最大值5冒泡到倒数第2 ✓
 * 
 * 第3轮（i=2，j从0到0）：
 *   j=0：3 > 1 → 交换 → [1, 3, 5, 8]
 *   全部排好 ✓
 * 
 * 结果：[1, 3, 5, 8]
 */

/**
 * @brief 冒泡排序
 * 
 * @param v 待排序的整数向量（引用传递）
 * 
 * @note 时间复杂度 O(n²)，空间复杂度 O(1)
 * @note 稳定排序算法，相同元素的相对顺序不变
 * @note 每轮将最大元素"冒泡"到未排序区的末尾
 */
void BubbleSort(vector<int>& v) {
    int len = v.size();
    // 外层循环：i 控制已排好元素个数
    // len-1 轮（最后一个自动排好）
    for (int i = 0; i < len - 1; ++i) {
        // 内层循环：j 控制比较范围
        // len-1-i：末尾 i 个已排好，不用再比较
        for (int j = 0; j < len - 1 - i; ++j) {
            // 如果当前 > 下一个，交换（大的往后）
            if (v[j] > v[j + 1]) {
                swap(v[j], v[j + 1]);
            }
        }
    }
}

/**
 * @brief 冒泡排序（模板版本）
 * @tparam T 元素类型（需支持 > 比较操作）
 * @param arr 待排序数组
 * @param len 数组长度
 * 
 * @note 适用于整数、浮点数及支持比较操作的自定义类型
 * @note 时间复杂度 O(n²)，空间复杂度 O(1)
 * @note 稳定排序算法，相同元素的相对顺序不变
 */
template<typename T> //整數或浮點數皆可使用,若要使用物件(class)時必須設定大於(>)的運算子功能
void bubble_sort(T arr[], int len) {
	for (int i = 0; i < len - 1; i++)
		for (int j = 0; j < len - 1 - i; j++)
			if (arr[j] > arr[j + 1])
				swap(arr[j], arr[j + 1]);
}

/**
 * @brief 冒泡排序（改进版）
 * 
 * 优化：如果某轮没有发生交换，说明已经有序
 *       提前结束排序
 */
void BubbleSort_orderly(vector<int>& v) {
    int len = v.size();
    bool orderly = false;  // 是否已有序
    
    for (int i = 0; i < len - 1 && !orderly; ++i) {
        orderly = true;  // 假设已有序
        for (int j = 0; j < len - 1 - i; ++j) {
            if (v[j] > v[j + 1]) {
                orderly = false;  // 发生交换，还未有序
                swap(v[j], v[j + 1]);
            }
        }
    }
}