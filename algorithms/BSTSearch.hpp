/*
 *（根节点，左子树，右子树）。通过比较关键字与根节点，递归地在左子树或右子树中查找。
 *
 * 二叉搜索树查找思路：
 * 1. 若树为空，则查找失败
 * 2. 若 key 等于根节点的关键字，则查找成功
 * 3. 若 key 小于根节点的关键字，则递归查找左子树
 * 4. 若 key 大于根节点的关键字，则递归查找右子树
 *
 * 查找算法	平均时间复杂度	最差时间复杂度	空间复杂度	数据对象稳定性
 * BST查找	O(log₂n)（平衡）	O(n)（退化为链表）	O(log n)	有序树
 * 二叉搜索树示例：        10
 *                       /  \
 *                      5    15
 *                     / \   / \
 *                    3   7 12  18
 * 
 * 查找目标值 7：
 *   第1步：从根节点 10 开始
 *     7 < 10 → 进入左子树
 *   第2步：当前节点 5
 *     7 > 5 → 进入右子树
 *   第3步：当前节点 7
 *     7 == 7 → 找到！返回节点 7
 * 
 * 查找目标值 12：
 *   第1步：从根节点 10 开始
 *     12 > 10 → 进入右子树
 *   第2步：当前节点 15
 *     12 < 15 → 进入左子树
 *   第3步：当前节点 12
 *     12 == 12 → 找到！返回节点 12
 * 
 * 查找目标值 4（不存在）：
 *   第1步：从根节点 10 开始
 *     4 < 10 → 进入左子树
 *   第2步：当前节点 5
 *     4 < 5 → 进入左子树
 *   第3步：当前节点 3
 *     4 > 3 → 进入右子树
 *   第4步：当前节点为空
 *     查找失败，返回 FALSE，p 指向节点 3
 * 
 * 查找目标值 20（不存在）：
 *   第1步：从根节点 10 开始
 *     20 > 10 → 进入右子树
 *   第2步：当前节点 15
 *     20 > 15 → 进入右子树
 *   第3步：当前节点 18
 *     20 > 18 → 进入右子树
 *   第4步：当前节点为空
 *     查找失败，返回 FALSE，p 指向节点 18
 * 
 * 结果：找到返回 TRUE 及节点指针；未找到返回 FALSE 及查找路径上最后一个节点指针
 */

/**
 * @brief 二叉搜索树节点结构体
 * 
 * @param data    关键字（KeyType类型）
 * @param lchild  左子树指针
 * @param rchild  右子树指针
 */
typedef struct BiTNode {
    KeyType data;
    struct BiTNode *lchild, *rchild;
} BiTNode, *BiTree;  

/**
 * @brief 在二叉搜索树中递归查找关键字
 * 
 * @param T     二叉搜索树的根节点指针
 * @param key   要查找的关键字
 * @param f     指向 T 的双亲节点，初始调用值为 NULL
 * @param p     查找成功时指向关键字所在的节点；查找失败时指向查找路径上访问的最后一个节点
 * 
 * @return Status 查找成功返回 TRUE，失败返回 FALSE
 * 
 * @note  时间复杂度 O(log n)（平衡树），最坏 O(n)
 * @note  空间复杂度 O(log n)（递归调用栈）
 * @note  要求树满足二叉搜索树性质：左子树 < 根节点 < 右子树
 */
Status SearchBST(BiTree T, KeyType key, BiTree f, BiTree &p) {
    // 递归终止条件：树为空，查找失败
    if (!T) {
        p = f;
        return FALSE;
    }
    // 查找成功：关键字等于根节点关键字
    else if (key == T->data.key) {
        p = T;
        return TRUE;
    }
    // 关键字小于根节点关键字，递归查找左子树
    else if (key < T->data.key) {
        return SearchBST(T->lchild, key, T, p);
    }
    // 关键字大于根节点关键字，递归查找右子树
    else {
        return SearchBST(T->rchild, key, T, p);
    }
}