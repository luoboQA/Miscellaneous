/*
 *（顺序遍历，逐个比较，哨兵优化）。从第一个元素开始逐个与目标值比较，直到找到目标或遍历完所有元素。
 *
 * 顺序查找思路：
 * 1. 从数组第一个元素开始
 * 2. 将当前元素与目标值进行比较
 * 3. 若相等，查找成功，返回当前位置
 * 4. 若不等，继续检查下一个元素
 * 5. 若遍历完所有元素仍未找到，查找失败，返回 -1
 *
 * 查找算法	平均时间复杂度	最差时间复杂度	最好时间复杂度	空间复杂度	查找条件
 * 顺序查找	O(n)	        O(n)	        O(1)	        O(1)	    无序或有序均可
 * 
 * 数组：[5, 2, 4, 6, 1, 3]
 * 
 * 标准版查找过程（查找 k=6）：
 *   i=0: v[0]=5 != 6 → 继续
 *   i=1: v[1]=2 != 6 → 继续
 *   i=2: v[2]=4 != 6 → 继续
 *   i=3: v[3]=6 == 6 → 找到！返回 3
 * 
 * 标准版查找过程（查找 k=7，不存在）：
 *   i=0: 5!=7 → i=1
 *   i=1: 2!=7 → i=2
 *   i=2: 4!=7 → i=3
 *   i=3: 6!=7 → i=4
 *   i=4: 1!=7 → i=5
 *   i=5: 3!=7 → i=6
 *   i=6: 6 < v.size()? 否 → 返回 -1
 * 
 * 哨兵版查找过程（查找 k=6）：
 *   原始数组：[5, 2, 4, 6, 1, 3]
 * 
 *   第1步：保存 last = v[5] = 3
 *   第2步：设置哨兵 v[5] = 6 → [5, 2, 4, 6, 1, 6]
 *   第3步：遍历（无需检查越界）
 *     i=0: 5!=6 → i=1
 *     i=1: 2!=6 → i=2
 *     i=2: 4!=6 → i=3
 *     i=3: 6==6 → 找到！退出
 *   第4步：恢复 v[5] = 3
 *   第5步：i=3 < n-1=5 → 返回 3 ✓
 * 
 * 哨兵版查找过程（查找 k=7，不存在）：
 *   第1步：保存 last = v[5] = 3
 *   第2步：设置哨兵 v[5] = 7 → [5, 2, 4, 6, 1, 7]
 *   第3步：遍历
 *     i=0: 5!=7 → i=1
 *     i=1: 2!=7 → i=2
 *     i=2: 4!=7 → i=3
 *     i=3: 6!=7 → i=4
 *     i=4: 1!=7 → i=5
 *     i=5: 7==7 → 找到哨兵！退出
 *   第4步：恢复 v[5] = 3
 *   第5步：i=5 < n-1? 否，且 v[5]=3 != 7 → 返回 -1
 * 
 * 标准版 vs 哨兵版：
 *   标准版：每次循环检查两个条件（i < n && v[i] == k）
 *   哨兵版：每次循环只检查一个条件（v[i] == k），性能略优
 *   哨兵版需要临时修改数组，但会恢复
 */

#include <vector>

/**
 * @brief 顺序查找（标准版）
 * 
 * @param v 待查找的整数向量
 * @param k 要查找的目标值
 * @return int 找到返回元素下标，未找到返回 -1
 * 
 * @note 时间复杂度 O(n)，空间复杂度 O(1)
 * @note 每次循环检查两个条件：i < n && v[i] == k
 * @note 适用于无序或有序数据
 */
int SequentialSearch(std::vector<int>& v, int k) {
    for (int i = 0; i < (int)v.size(); ++i) {
        if (v[i] == k) {
            return i;
        }
    }
    return -1;
}

/**
 * @brief 顺序查找（哨兵版）
 * 
 * @param v 待查找的整数向量
 * @param k 要查找的目标值
 * @return int 找到返回元素下标，未找到返回 -1
 * 
 * @note 时间复杂度 O(n)，空间复杂度 O(1)
 * @note 在数组末尾设置哨兵，每次循环只需检查一个条件
 * @note 性能略优于标准版
 * @note 会临时修改数组，但会恢复
 */
int BetterSequentialSearch(std::vector<int>& v, int k) {
    int last = v[v.size() - 1];
    
    v[v.size() - 1] = k;
    
    int i = 0;
    while (v[i] != k) {
        i++;
    }
    
    v[v.size() - 1] = last;
    
    if (i < (int)v.size() - 1 || v[v.size() - 1] == k) {
        return i;
    }
    return -1;
}
