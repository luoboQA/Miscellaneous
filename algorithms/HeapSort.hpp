/*
 *（最大堆，堆顶，交换）。通过构建最大堆，将堆顶最大值交换到末尾，再调整剩余元素。
 *
 * 堆排序思路：
 * 1. 将待排序序列构造成一个大顶堆（最大堆）
 * 2. 此时，整个序列的最大值就是堆顶的根节点
 * 3. 将其与末尾元素进行交换，此时末尾就是最大值
 * 4. 然后将剩余 n-1 个元素重新构造成一个堆
 * 5. 重复步骤 3-4，直到整个序列有序
 *
 * 排序算法	平均时间复杂度	最差时间复杂度	空间复杂度	数据对象稳定性
 * 堆排序	O(n*log₂n)	O(n*log₂n)	O(1)	    不稳定
 * 
 * 数组：[3, 5, 8, 4, 1]（按完全二叉树存储）
 * 
 * 第1步：构建初始最大堆
 *   从最后一个非叶子节点开始调整（len/2-1 = 1）
 *   调整位置1（值5）：子节点4和1 → 5>4且5>1 → 不变
 *   调整位置0（值3）：子节点5和8 → 8最大 → 交换3和8
 *     [8, 5, 3, 4, 1]
 *   继续调整位置0（值3）：子节点4和1 → 4最大 → 交换3和4
 *     [8, 5, 4, 3, 1]
 *   最大堆构建完成：[8, 5, 4, 3, 1]
 * 
 * 第2步：交换堆顶与末尾（最大放最后）
 *   交换arr[0]=8 和 arr[4]=1 → [1, 5, 4, 3, 8]
 *   调整剩余元素（0到3）：
 *     调整位置0（值1）：子节点5和4 → 5最大 → 交换1和5
 *       [5, 1, 4, 3, 8]
 *     继续调整位置1（值1）：子节点3 → 3>1 → 交换1和3
 *       [5, 3, 4, 1, 8]
 * 
 * 第3步：交换堆顶与末尾（第二大的放倒数第二）
 *   交换arr[0]=5 和 arr[3]=1 → [1, 3, 4, 5, 8]
 *   调整剩余元素（0到2）：
 *     调整位置0（值1）：子节点3和4 → 4最大 → 交换1和4
 *       [4, 3, 1, 5, 8]
 * 
 * 第4步：交换堆顶与末尾
 *   交换arr[0]=4 和 arr[2]=1 → [1, 3, 4, 5, 8]
 *   调整剩余元素（0到1）：
 *     调整位置0（值1）：子节点3 → 3>1 → 交换1和3
 *       [3, 1, 4, 5, 8]
 * 
 * 第5步：交换堆顶与末尾
 *   交换arr[0]=3 和 arr[1]=1 → [1, 3, 4, 5, 8]
 *   调整剩余元素（0到0）：无需调整
 * 
 * 最终结果：[1, 3, 4, 5, 8]
 * 
 * 堆的性质：
 *   - 大顶堆：每个节点的值都大于或等于其子节点的值
 *   - 小顶堆：每个节点的值都小于或等于其子节点的值
 *   - 下标关系：父节点下标为 i，左子节点为 2*i+1，右子节点为 2*i+2
 */


/**
 * @brief 维护最大堆的性质（堆化）
 * 
 * 将以 start 为根的子树调整为最大堆，前提是 start 的子树已经是最大堆
 * 
 * @param arr   待调整的数组
 * @param start 起始节点的下标（父节点）
 * @param end   结束节点的下标（最后一个元素）
 * 
 * @note 时间复杂度 O(log₂n)
 * @note 向下调整：从父节点开始，与较大的子节点比较，若小于则交换
 */
void max_heapify(int arr[], int start, int end) {
    int dad = start;
    int son = dad * 2 + 1;
    
    while (son <= end) {
        if (son + 1 <= end && arr[son] < arr[son + 1]) {
            son++;
        }
        
        if (arr[dad] > arr[son]) {
            return;
        }
        
        std::swap(arr[dad], arr[son]);
        dad = son;
        son = dad * 2 + 1;
    }
}

/**
 * @brief 堆排序主函数
 * 
 * @param arr 待排序的整数数组
 * @param len 数组长度
 * 
 * @note 使用最大堆进行升序排序
 * @note 时间复杂度 O(n*log₂n)，空间复杂度 O(1)
 * @note 不稳定排序
 */
void heap_sort(int arr[], int len) {
    for (int i = len / 2 - 1; i >= 0; i--) {
        max_heapify(arr, i, len - 1);
    }
    
    for (int i = len - 1; i > 0; i--) {
        std::swap(arr[0], arr[i]);
        max_heapify(arr, 0, i - 1);
    }
}