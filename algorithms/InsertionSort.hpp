/*
 *（已排序区间，未排序区间，插入）。将未排序元素逐个插入到已排序区间的正确位置。
 *
 * 插入排序思路：
 * 1. 从第一个元素开始，该元素可以认为已经被排序
 * 2. 取出下一个元素，在已经排序的元素序列中从后向前扫描
 * 3. 如果该元素（已排序）大于新元素，将该元素移到下一位置
 * 4. 重复步骤3，直到找到已排序的元素小于或者等于新元素的位置
 * 5. 将新元素插入到该位置后
 * 6. 重复步骤2~5，直到所有元素有序
 *
 * 排序算法	平均时间复杂度	最差时间复杂度	最好时间复杂度	空间复杂度	数据对象稳定性
 * 插入排序	O(n²)	        O(n²)	        O(n)	        O(1)	    稳定
 * 数组：[5, 2, 4, 6, 1, 3]
 * 
 * 第1次（i=1，插入2）：
 *   已排序：[5]，取出2
 *   5 > 2 → 5后移 → [5, 5, 4, 6, 1, 3]
 *   j=-1 → 插入2到位置0 → [2, 5, 4, 6, 1, 3]
 * 
 * 第2次（i=2，插入4）：
 *   已排序：[2, 5]，取出4
 *   5 > 4 → 5后移 → [2, 5, 5, 6, 1, 3]
 *   2 <= 4 → 插入4到位置1 → [2, 4, 5, 6, 1, 3]
 * 
 * 第3次（i=3，插入6）：
 *   已排序：[2, 4, 5]，取出6
 *   5 <= 6 → 插入6到位置3 → [2, 4, 5, 6, 1, 3]
 * 
 * 第4次（i=4，插入1）：
 *   已排序：[2, 4, 5, 6]，取出1
 *   6 > 1 → 6后移 → [2, 4, 5, 6, 6, 3]
 *   5 > 1 → 5后移 → [2, 4, 5, 5, 6, 3]
 *   4 > 1 → 4后移 → [2, 4, 4, 5, 6, 3]
 *   2 > 1 → 2后移 → [2, 2, 4, 5, 6, 3]
 *   j=-1 → 插入1到位置0 → [1, 2, 4, 5, 6, 3]
 * 
 * 第5次（i=5，插入3）：
 *   已排序：[1, 2, 4, 5, 6]，取出3
 *   6 > 3 → 6后移 → [1, 2, 4, 5, 6, 6]
 *   5 > 3 → 5后移 → [1, 2, 4, 5, 5, 6]
 *   4 > 3 → 4后移 → [1, 2, 4, 4, 5, 6]
 *   2 <= 3 → 插入3到位置2 → [1, 2, 3, 4, 5, 6]
 * 
 * 结果：[1, 2, 3, 4, 5, 6]
 * 
 * 适用场景：
 *   - 数据量较小（通常 n < 100）
 *   - 数据基本有序
 *   - 对稳定性有要求
 */


/**
 * @brief 插入排序主函数
 * 
 * @param v 待排序的整数向量（引用传递）
 * 
 * @note 时间复杂度 O(n²)，空间复杂度 O(1)
 * @note 稳定排序算法，相同元素的相对顺序不变
 * @note 当数据量较小或基本有序时效率较高
 */
void InsertSort(std::vector<int>& v) {
    int len = v.size();
    
    for (int i = 1; i < len; ++i) {
        int temp = v[i];
        
        int j = i - 1;
        while (j >= 0 && v[j] > temp) {
            v[j + 1] = v[j];
            j--;
        }
        
        v[j + 1] = temp;
    }
}