/*
 *（已排序区间，未排序区间，选择）。每次从未排序区间选择最小元素放到已排序区间末尾。
 *
 * 选择排序思路：
 * 1. 在未排序序列中找到最小元素
 * 2. 将最小元素与未排序序列的第一个元素交换
 * 3. 将已排序序列范围扩大一位
 * 4. 重复步骤1-3，直到所有元素有序
 *
 * 排序算法	平均时间复杂度	最差时间复杂度	空间复杂度	数据对象稳定性
 * 选择排序	O(n²)	        O(n²)	        O(1)	    不稳定
 * 
 * 数组：[64, 25, 12, 22, 11]
 * 
 * 第1次（i=0，未排序：[64,25,12,22,11]）：
 *   找最小值：11（索引4）
 *   交换arr[0]和arr[4] → [11, 25, 12, 22, 64]
 *   已排序：[11]
 * 
 * 第2次（i=1，未排序：[25,12,22,64]）：
 *   找最小值：12（索引2）
 *   交换arr[1]和arr[2] → [11, 12, 25, 22, 64]
 *   已排序：[11, 12]
 * 
 * 第3次（i=2，未排序：[25,22,64]）：
 *   找最小值：22（索引3）
 *   交换arr[2]和arr[3] → [11, 12, 22, 25, 64]
 *   已排序：[11, 12, 22]
 * 
 * 第4次（i=3，未排序：[25,64]）：
 *   找最小值：25（索引3）
 *   交换arr[3]和arr[3] → [11, 12, 22, 25, 64]
 *   已排序：[11, 12, 22, 25]
 * 
 * 结果：[11, 12, 22, 25, 64]
 * 
 * 特点：交换次数最少（最多n-1次），适合交换成本高的场景
 *       不稳定（如[5,8,5,2]第一次交换会将两个5的相对顺序改变）
 */

#include <vector>
#include <algorithm>

/**
 * @brief 选择排序主函数
 * 
 * @param v 待排序的整数向量（引用传递）
 * 
 * @note 时间复杂度 O(n²)，空间复杂度 O(1)
 * @note 不稳定排序算法
 * @note 每次选择未排序区间的最小值
 */
void SelectionSort(std::vector<int>& v) {
    int len = v.size();
    
    for (int i = 0; i < len - 1; i++) {
        int minIdx = i;
        for (int j = i + 1; j < len; j++) {
            if (v[j] < v[minIdx]) {
                minIdx = j;
            }
        }
        if (minIdx != i) {
            std::swap(v[i], v[minIdx]);
        }
    }
}